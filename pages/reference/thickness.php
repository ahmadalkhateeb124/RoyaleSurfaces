      <span class="thickness-size">2cm</span>
      <h2>Two Centimetre</h2>
      <p>Roughly ¾ inch. Lighter and cheaper per slab, but exposed edges usually need a laminated build-up to avoid looking thin, and most installs want a plywood substrate underneath.</p>
      <ul class="check-list">
        <li>Vanities and smaller runs</li>
        <li>Vertical work — backsplashes, shower walls, fireplace faces</li>
        <li>Anywhere weight is a structural concern</li>
      </ul>
    </article>

    <article class="thickness-card is-primary" data-reveal>
      <span class="thickness-size">3cm</span>
      <h2>Three Centimetre</h2>
      <p>Roughly 1¼ inch, and the default for kitchen work in the US. Strong enough to span cabinet runs without a substrate, and it carries a mitred edge cleanly if you want a thicker look.</p>
      <ul class="check-list">
        <li>Kitchen counters and islands</li>
        <li>Outdoor kitchens and bars</li>
        <li>Any run with an unsupported overhang</li>
      </ul>
    </article>

    <article class="thickness-card" data-reveal>
      <span class="thickness-size">6&ndash;12mm</span>
      <h2>Porcelain</h2>
      <p>Large-format porcelain comes far thinner than stone. The weight saving is often what makes a project viable — cladding an occupied floor, or surfacing over an existing substrate without rebuilding it.</p>
      <ul class="check-list">
        <li>Wall cladding and feature walls</li>
        <li>Surfacing over existing surfaces</li>
        <li>Projects with a weight limit</li>
      </ul>
    </article>
  </div>

  <div class="prose" style="max-width:78ch;margin-top:48px;">
    <h2>Decide thickness before you choose a slab</h2>
    <p>Not every material is stocked in every thickness. Committing to a stone and then discovering it only comes in 2cm — when your design assumed 3cm — means starting the selection over. Settle thickness first and the search narrows honestly.</p>
    <h2>Mitred edges</h2>
    <p>If you want the look of a 6cm edge, that is a mitre: two pieces joined at 45° to form a hollow thick edge. It consumes more material and more shop time, so factor it into both budget and slab count.</p>
